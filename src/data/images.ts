/* ───────────── helpers ───────────── */

export const RESPONSIVE_WIDTHS = [640, 1280] as const
const BASE: string = import.meta.env?.BASE_URL ?? './'

/** A photo may be requested from the network only when it is verified and credited. */
export function isPhotoReady(ph: Photo | undefined): boolean {
  return !!ph && ph.status === 'ready' && !!ph.photographer && !!ph.license && !!ph.source && !!ph.sourceUrl
}

export function photoSrc(ph: Photo, w?: (typeof RESPONSIVE_WIDTHS)[number]) {
  const path = w && ph.responsive ? ph.url.replace(/\.webp$/, `-${w}.webp`) : ph.url
  return BASE + path
}

export function photoSrcSet(ph: Photo) {
  if (!ph.responsive) return undefined
  return [...RESPONSIVE_WIDTHS.map((w) => `${photoSrc(ph, w)} ${w}w`), `${photoSrc(ph)} 1920w`].join(', ')
}

function hash(s: string) {
  let h = 2166136261
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619)
  return h >>> 0
}

/** Deterministic photo for a landscape kind (different seeds → different photos of the pool). */
export function photoForScene(kind: SceneKind, seed: string = kind): Photo {
  const pool = scenePhotos[kind]
  const ready = pool.filter((id) => isPhotoReady(photoById[id]))
  const list = ready.length ? ready : pool
  return photoById[list[hash(seed) % list.length]]
}

/**
 * Ordered list of real photos to try after `ph` fails to load: explicit fallbacks first, then other
 * verified photos of the same category. Only ready photos are returned.
 */
export function fallbackChain(ph: Photo): Photo[] {
  const ids = [...(ph.fallbacks ?? []), ...photos.filter((x) => x.category === ph.category && x.id !== ph.id).map((x) => x.id)]
  const seen = new Set<string>([ph.id])
  const out: Photo[] = []
  for (const id of ids) {
    if (seen.has(id)) continue
    seen.add(id)
    const f = photoById[id]
    if (isPhotoReady(f)) out.push(f)
  }
  return out
}

