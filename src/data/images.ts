import type { L, ModuleId, SceneKind } from '../types'

/**
 * Central photo catalogue of the course.
 *
 * Every image used anywhere on the site has exactly one entry here. An entry describes the REAL
 * subject that must be photographed (place in Kyrgyzstan, what has to be in the frame) and, once a
 * verified photo is added, its authorship and licence.
 *
 * Rules:
 *  - `status: 'pending'` → the file is not in the repository yet. Components render a neutral
 *    «Фото будет добавлено» placeholder and make NO network request (no broken links).
 *  - `status: 'ready'` is allowed only when the file exists in `public/<url>` AND `photographer`,
 *    `source`, `sourceUrl` and `license` are filled from the original source page.
 *  - Only photos taken in Kyrgyzstan (exception: species photos may be from the natural range of
 *    the species — then `location` must say where it was really taken).
 *
 * Files: `public/photos/<folder>/<id>.webp` (1920 px wide) + optional responsive variants
 * `<id>-640.webp`, `<id>-1280.webp` (set `responsive: true`). `scripts/prepare_photos.py` makes all
 * three from an original; `npm run photos:check` validates the catalogue against the files.
 */

export type PhotoCategory = 'mountains' | 'lakes' | 'rivers' | 'forests' | 'plants' | 'wildlife' | 'valleys' | 'glaciers'
export type PhotoFolder = 'geography' | 'relief' | 'climate' | 'water' | 'vegetation' | 'forests' | 'gallery'
export type PhotoStatus = 'pending' | 'ready'

export interface Photo {
  id: string
  title: L
  category: PhotoCategory
  folder: PhotoFolder
  /** path relative to the site root (public/), e.g. `photos/water/water-issyk-kul.webp` */
  url: string
  location: L
  description: L
  /** Exactly what the photo must show (used for the placeholder and the list of required photos). */
  brief: L
  /** recommended orientation / frame */
  aspect: '16:9' | '3:2' | '4:3' | '4:5' | '21:9'
  /** minimal width of the original in px */
  minWidth: number
  /** CSS object-position for good cropping, e.g. '50% 35%' */
  focus?: string
  status: PhotoStatus
  photographer?: string
  /** name of the source: Wikimedia Commons, Unsplash, Pexels… */
  source?: string
  /** page of the original photo */
  sourceUrl?: string
  /** short licence name, e.g. CC BY-SA 4.0 */
  license?: string
  licenseUrl?: string
  /** pixel size of the 1920 master (for layout); */
  width?: number
  height?: number
  /** `<id>-640.webp` and `<id>-1280.webp` exist */
  responsive?: boolean
  /** explicit fallbacks (other real photos), tried before same-category photos */
  fallbacks?: string[]
}

type Draft = Omit<Photo, 'url' | 'status'> & { status?: PhotoStatus }

const K = (ru: string, ky: string): L => ({ ru, ky })

function p(d: Draft): Photo {
  return { status: 'pending', ...d, url: `photos/${d.folder}/${d.id}.webp` }
}

